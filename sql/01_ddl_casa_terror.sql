SET DEFINE OFF;

-- ---------------------------------------------------------------------
-- DIMENSION 1: TIPO_EXPERIENCIA
-- Modalidad de la venta y sus reglas (atraccion general o reserva
-- personalizada).
-- ---------------------------------------------------------------------
CREATE TABLE tipo_experiencia (
    te_id_tipos_experiencia     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    te_nombre                   VARCHAR2(50)  NOT NULL,
    te_descripcion              VARCHAR2(200),
    te_permite_personalizacion  VARCHAR2(2)   NOT NULL,
    te_requiere_reserva         VARCHAR2(2)   NOT NULL,
    te_recargo_porcentaje       NUMBER(5,2)   DEFAULT 0 NOT NULL,
    CONSTRAINT pk_id_tipos_experiencia PRIMARY KEY (te_id_tipos_experiencia),
    CONSTRAINT uq_tipos_nombre         UNIQUE (te_nombre),
    CONSTRAINT ck_personalizacion_tipos CHECK (te_permite_personalizacion IN ('SI','NO')),
    CONSTRAINT ck_requiere_reserva_tipos CHECK (te_requiere_reserva IN ('SI','NO')),
    CONSTRAINT ck_recargo_tipos        CHECK (te_recargo_porcentaje BETWEEN 0 AND 100)
);

-- ---------------------------------------------------------------------
-- DIMENSION 2: CLIENTE
-- Quien compra. La fila 1 es el VISITANTE GENERAL (taquilla sin registro).
-- ---------------------------------------------------------------------
CREATE TABLE cliente (
    c_id_clientes        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    c_tipo_documento     VARCHAR2(20)  NOT NULL,
    c_numero_documento   VARCHAR2(30)  NOT NULL,
    c_nombre             VARCHAR2(100) NOT NULL,
    c_apellido           VARCHAR2(100),
    c_correo             VARCHAR2(150),
    c_telefono           VARCHAR2(20),
    c_fecha_nacimiento   DATE,
    c_fecha_registro     DATE          DEFAULT SYSDATE NOT NULL,
    c_estado             VARCHAR2(20)  NOT NULL,
    CONSTRAINT pk_id_clientes            PRIMARY KEY (c_id_clientes),
    CONSTRAINT uq_clientes_documento     UNIQUE (c_numero_documento),
    CONSTRAINT uq_clientes_correo        UNIQUE (c_correo),
    CONSTRAINT ck_tipo_documento_clientes CHECK (c_tipo_documento IN ('CC','CE','TI','PASAPORTE','NA')),
    CONSTRAINT ck_estado_clientes        CHECK (c_estado IN ('ACTIVO','INACTIVO')),
    -- Adicion al Taller: formato basico de correo (valores vacios permitidos).
    CONSTRAINT ck_correo_clientes        CHECK (c_correo IS NULL
                                                OR REGEXP_LIKE(c_correo, '^[^@ ]+@[^@ ]+\.[^@ ]+$'))
);

-- ---------------------------------------------------------------------
-- DIMENSION 3: EXPERIENCIA
-- Catalogo de atracciones y recorridos. Solo el administrador lo modifica.
-- ---------------------------------------------------------------------
CREATE TABLE experiencia (
    ex_id_experiencias   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ex_nombre            VARCHAR2(100) NOT NULL,
    ex_tematica          VARCHAR2(50)  NOT NULL,
    ex_descripcion       VARCHAR2(500),
    ex_duracion_minutos  NUMBER        NOT NULL,
    ex_precio_base       NUMBER(10,2)  NOT NULL,
    ex_capacidad_maxima  NUMBER        NOT NULL,
    ex_edad_minima       NUMBER(2)     DEFAULT 12 NOT NULL,
    ex_estado            VARCHAR2(20)  NOT NULL,
    CONSTRAINT pk_id_experiencias        PRIMARY KEY (ex_id_experiencias),
    CONSTRAINT uq_experiencias_nombre    UNIQUE (ex_nombre),
    CONSTRAINT ck_tematica_experiencias  CHECK (ex_tematica IN
        ('ZOMBIES','FANTASMAS','HOSPITAL ABANDONADO',
         'PSICOL' || UNISTR('\00D3') || 'GICO','SLASHER','OCULTISMO','OTRA')),
    CONSTRAINT ck_duracion_experiencias  CHECK (ex_duracion_minutos > 0),
    CONSTRAINT ck_precio_experiencias    CHECK (ex_precio_base >= 0),
    CONSTRAINT ck_capacidad_experiencias CHECK (ex_capacidad_maxima > 0),
    CONSTRAINT ck_edad_minima_experiencias CHECK (ex_edad_minima BETWEEN 0 AND 99),
    CONSTRAINT ck_estado_experiencias    CHECK (ex_estado IN ('ACTIVA','INACTIVA','MANTENIMIENTO'))
);

-- ---------------------------------------------------------------------
-- DIMENSION 4: SESION
-- Horario concreto de UNA experiencia: fecha, hora, zona y cupos. Solo el
-- administrador la crea o la modifica; la venta solo descuenta cupos.
-- ---------------------------------------------------------------------
CREATE TABLE sesion (
    s_id_sesiones         NUMBER GENERATED BY DEFAULT AS IDENTITY,
    s_id_experiencias     NUMBER       NOT NULL,
    s_fecha               DATE         NOT NULL,
    s_hora_inicio         VARCHAR2(5)  NOT NULL,
    s_zona                VARCHAR2(50) NOT NULL,
    s_cupos_totales       NUMBER       NOT NULL,
    s_cupos_disponibles   NUMBER       NOT NULL,
    s_estado              VARCHAR2(20) NOT NULL,
    CONSTRAINT pk_id_sesiones            PRIMARY KEY (s_id_sesiones),
    CONSTRAINT fk_sesiones_experiencias  FOREIGN KEY (s_id_experiencias) REFERENCES experiencia (ex_id_experiencias),
    CONSTRAINT uq_sesiones_fecha_hora_zona UNIQUE (s_fecha, s_hora_inicio, s_zona),
    CONSTRAINT ck_hora_inicio_sesiones   CHECK (REGEXP_LIKE(s_hora_inicio, '^([01][0-9]|2[0-3]):[0-5][0-9]$')),
    CONSTRAINT ck_cupos_totales_sesiones CHECK (s_cupos_totales > 0),
    CONSTRAINT ck_cupos_disponibles_sesiones CHECK (s_cupos_disponibles >= 0
                                                    AND s_cupos_disponibles <= s_cupos_totales),
    CONSTRAINT ck_estado_sesiones        CHECK (s_estado IN
        ('PROGRAMADA','EN CURSO','FINALIZADA','CANCELADA'))
);

-- ---------------------------------------------------------------------
-- TABLA DE HECHOS: VENTA
-- Grano: una fila = una compra de entradas o una reserva para una sesion.
-- ---------------------------------------------------------------------
CREATE TABLE venta (
    v_id_ventas             NUMBER GENERATED BY DEFAULT AS IDENTITY,
    v_id_clientes           NUMBER        NOT NULL,
    v_id_experiencias       NUMBER        NOT NULL,
    v_id_sesiones           NUMBER        NOT NULL,
    v_id_tipos_experiencia  NUMBER        NOT NULL,
    v_fecha_registro        TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    v_cantidad_personas     NUMBER        NOT NULL,
    v_valor_unitario        NUMBER(10,2)  NOT NULL,
    v_recargo               NUMBER(10,2)  DEFAULT 0 NOT NULL,
    v_valor_total           NUMBER(12,2)  NOT NULL,
    v_nivel_intensidad      VARCHAR2(10),
    v_actores_en_vivo       VARCHAR2(2)   DEFAULT 'NO' NOT NULL,
    v_efectos_especiales    VARCHAR2(2)   DEFAULT 'NO' NOT NULL,
    v_motivo_celebracion    VARCHAR2(30),
    v_notas                 VARCHAR2(500),
    v_metodo_pago           VARCHAR2(20)  NOT NULL,
    v_estado                VARCHAR2(20)  NOT NULL,
    CONSTRAINT pk_id_ventas       PRIMARY KEY (v_id_ventas),
    CONSTRAINT fk_ventas_clientes     FOREIGN KEY (v_id_clientes)          REFERENCES cliente (c_id_clientes),
    CONSTRAINT fk_ventas_experiencias FOREIGN KEY (v_id_experiencias)      REFERENCES experiencia (ex_id_experiencias),
    CONSTRAINT fk_ventas_sesiones     FOREIGN KEY (v_id_sesiones)          REFERENCES sesion (s_id_sesiones),
    CONSTRAINT fk_ventas_tipos        FOREIGN KEY (v_id_tipos_experiencia) REFERENCES tipo_experiencia (te_id_tipos_experiencia),
    CONSTRAINT ck_cantidad_ventas        CHECK (v_cantidad_personas > 0),
    CONSTRAINT ck_valor_unitario_ventas  CHECK (v_valor_unitario >= 0),
    CONSTRAINT ck_recargo_ventas         CHECK (v_recargo >= 0),
    CONSTRAINT ck_valor_total_ventas     CHECK (v_valor_total = v_cantidad_personas * v_valor_unitario + v_recargo),
    CONSTRAINT ck_intensidad_ventas      CHECK (v_nivel_intensidad IN ('SUAVE','MEDIA','EXTREMA')),
    CONSTRAINT ck_actores_ventas         CHECK (v_actores_en_vivo IN ('SI','NO')),
    CONSTRAINT ck_efectos_ventas         CHECK (v_efectos_especiales IN ('SI','NO')),
    CONSTRAINT ck_celebracion_ventas     CHECK (v_motivo_celebracion IN
        ('CUMPLEA' || UNISTR('\00D1') || 'OS','DESPEDIDA','EMPRESARIAL','ANIVERSARIO','NINGUNO')),
    CONSTRAINT ck_metodo_pago_ventas     CHECK (v_metodo_pago IN ('EFECTIVO','TARJETA','TRANSFERENCIA','PSE')),
    CONSTRAINT ck_estado_ventas          CHECK (v_estado IN
        ('PENDIENTE','CONFIRMADA','CANCELADA',
         'ASISTI' || UNISTR('\00D3'),'NO ASISTI' || UNISTR('\00D3'))),
    CONSTRAINT ck_coherencia_personalizacion_ventas CHECK (
        v_nivel_intensidad IS NOT NULL
        OR (v_actores_en_vivo = 'NO' AND v_efectos_especiales = 'NO'))
);

-- ---------------------------------------------------------------------
-- INDICES (adicion tecnica, no cambia el modelo): Oracle no indexa las
-- llaves foraneas solas; con estos indices los JOIN del panel y del
-- historial del cliente son rapidos.
-- ---------------------------------------------------------------------
CREATE INDEX ix_ventas_clientes     ON venta (v_id_clientes);
CREATE INDEX ix_ventas_experiencias ON venta (v_id_experiencias);
CREATE INDEX ix_ventas_sesiones     ON venta (v_id_sesiones);
CREATE INDEX ix_ventas_tipos        ON venta (v_id_tipos_experiencia);
CREATE INDEX ix_ventas_fecha        ON venta (v_fecha_registro);
CREATE INDEX ix_sesiones_fecha      ON sesion (s_fecha);
CREATE INDEX ix_sesiones_experiencias ON sesion (s_id_experiencias);

-- Verificacion rapida: deben aparecer las 5 tablas.
SELECT table_name FROM user_tables
WHERE table_name IN ('TIPO_EXPERIENCIA','CLIENTE','EXPERIENCIA','SESION','VENTA')
ORDER BY table_name;
